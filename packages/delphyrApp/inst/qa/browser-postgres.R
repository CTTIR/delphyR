# Run preview-postgres.R first with a new synthetic fixture.
source("packages/delphyrApp/inst/qa/browser-helpers.R")
local({
  s <- qa_session()
  on.exit(s$close())
  qa_open(s, "http://127.0.0.1:3868")
  s$wait_for("Boolean(document.getElementById('panel-enrollment') && document.getElementById('panel-enrollment').value)", tries = 1200L)
  s$click("panel-load")
  s$wait_for("Boolean(document.getElementById('panel-consent_check') && document.querySelector('#panel-slot_1-form fieldset'))", tries = 1200L)
  stopifnot(isTRUE(s$js("document.querySelector('#panel-slot_1-form fieldset').disabled")))
  s$click("panel-consent_check")
  s$click("panel-consent")
  s$wait_for("Boolean(document.querySelector('#panel-slot_1-form fieldset') && !document.querySelector('#panel-slot_1-form fieldset').disabled)", tries = 1200L)
  # Consent rebuilds the block; its new controls have new generation ids.
  value_id <- s$js("document.querySelector('[id^=\"panel-item_\"][id$=\"-value\"]').id")
  save_id <- s$js("document.querySelector('[id^=\"panel-item_\"][id$=\"-save\"]').id")
  stopifnot(identical(s$value(value_id), ""))
  s$select(value_id, "7")
  s$wait_text("panel-card_1-status", "Not saved yet.", tries = 1200L)
  s$select("language", "de")
  s$wait_text("panel-card_1-status", "Noch nicht gespeichert.", tries = 1200L)
  stopifnot(identical(s$value(value_id), "7"))
  stopifnot(grepl("Synthetisches Beispielitem", s$text("panel-slot_1-title"), fixed = TRUE))
  s$click(save_id)
  s$wait_text("panel-card_1-status", "Gespeichert", tries = 1200L)
  print(s$text("panel-card_1-status"))
  s$click("panel-confirm")
  s$click("panel-submit")
  s$wait_text("panel-receipt", "Abgabe best\u00e4tigt:", tries = 1200L)
  receipt <- s$js("document.querySelector('#panel-receipt .del-ref').title")
  stopifnot(length(receipt) == 1L, grepl("^[0-9a-f-]{36}$", receipt))
  stopifnot(grepl("Europe/Berlin", s$text("panel-receipt"), fixed = TRUE))
  print(list(receipt = receipt, confirmation = s$text("panel-receipt")))
})
